// ===== FUNCIÓN PARA CAMBIAR IDIOMA =====
function changeLanguage(lang) {
    const elements = translations[lang];
    if (!elements) return;

    // Navegación
    const navElements = {
        'nav-inicio': 'inicio',
        'nav-historia': 'historia',
        'nav-quienes': 'quienesSomos',
        'nav-proyectos': 'proyectos',
        'nav-transparencia': 'transparencia',
        'nav-contacto': 'contacto',
        'btn-donar-header': 'donar'
    };
    
    Object.entries(navElements).forEach(([id, key]) => {
        const element = document.getElementById(id);
        if (element) element.textContent = elements[key];
    });

    // Contenido principal
    const contentElements = {
        'page-title': 'pageTitle',
        'page-subtitle': 'pageSubtitle',
        'hero-quote': 'heroQuote',
        'hero-author': 'heroAuthor',
        'our-story-title': 'ourStoryTitle',
        'mvv-title': 'mvvTitle',
        'mission-title': 'missionTitle',
        'mission-text': 'missionText',
        'vision-title': 'visionTitle',
        'vision-text': 'visionText',
        'values-title': 'valuesTitle',
        'values-text': 'valuesText'
    };
    
    Object.entries(contentElements).forEach(([id, key]) => {
        const element = document.getElementById(id);
        if (element) element.textContent = elements[key];
    });

    // Historia (con innerHTML para mantener <strong>)
    const historyElements = {
        'story-text-1': 'storyText1',
        'story-text-2': 'storyText2',
        'story-text-3': 'storyText3'
    };
    
    Object.entries(historyElements).forEach(([id, key]) => {
        const element = document.getElementById(id);
        if (element) element.innerHTML = elements[key];
    });

    // Valores individuales (solo 5 ahora)
    for (let i = 1; i <= 5; i++) {
        const nameElement = document.getElementById(`value-${i}-name`);
        const descElement = document.getElementById(`value-${i}-desc`);
        if (nameElement) nameElement.textContent = elements[`value${i}Name`];
        if (descElement) descElement.textContent = elements[`value${i}Desc`];
    }

    // Impacto
    const impactElements = {
        'impact-title': 'impactTitle',
        'impact-families': 'impactFamilies',
        'impact-years': 'impactYears',
        'impact-visitors': 'impactVisitors',
        'impact-testimonies': 'impactTestimonies',
        'impact-houses': 'impactHouses'
    };
    
    Object.entries(impactElements).forEach(([id, key]) => {
        const element = document.getElementById(id);
        if (element) element.textContent = elements[key];
    });

    // Equipo
    const teamTitle = document.getElementById('team-title');
    if (teamTitle) teamTitle.textContent = elements.teamTitle;
    
    for (let i = 1; i <= 6; i++) {
        const nameElement = document.getElementById(`member-${i}-name`);
        const roleElement = document.getElementById(`member-${i}-role`);
        const bioElement = document.getElementById(`member-${i}-bio`);
        
        if (nameElement && elements[`member${i}Name`]) {
            nameElement.textContent = elements[`member${i}Name`];
        }
        if (roleElement && elements[`member${i}Role`]) {
            roleElement.textContent = elements[`member${i}Role`];
        }
        if (bioElement && elements[`member${i}Bio`]) {
            bioElement.textContent = elements[`member${i}Bio`];
        }
    }

    // Cronología
    const timelineTitle = document.getElementById('timeline-title');
    if (timelineTitle) timelineTitle.textContent = elements.timelineTitle;
    
    const timelineYears = ['2016', '2018', '2019', '2020', '2022', '2024', '2025'];
    timelineYears.forEach(year => {
        const element = document.getElementById(`timeline-${year}`);
        if (element) element.textContent = elements[`timeline${year}`];
    });

    // Footer
    const footerElements = {
        'footer-contact-title': 'footerContactTitle',
        'footer-follow-title': 'footerFollowTitle',
        'footer-collaborate-title': 'footerCollaborateTitle',
        'footer-donate-btn': 'footerDonateBtn',
        'footer-donate-text': 'footerDonateText',
        'footer-copyright': 'footerCopyright'
    };
    
    Object.entries(footerElements).forEach(([id, key]) => {
        const element = document.getElementById(id);
        if (element) element.textContent = elements[key];
    });

    // IMPORTANTE: Guardar idioma seleccionado en localStorage
    localStorage.setItem('selectedLanguage', lang);
    document.documentElement.lang = lang;
}

// ===== EVENT LISTENER PARA EL SELECTOR DE IDIOMAS =====
document.addEventListener('DOMContentLoaded', function() {
    const languageSelect = document.getElementById('languageSelect');
    if (languageSelect) {
        // Cargar idioma guardado
        const savedLanguage = localStorage.getItem('selectedLanguage') || 'es';
        languageSelect.value = savedLanguage;
        
        // Aplicar idioma guardado si no es español
        if (savedLanguage !== 'es') {
            changeLanguage(savedLanguage);
        }
        
        // Escuchar cambios en el selector
        languageSelect.addEventListener('change', (e) => {
            changeLanguage(e.target.value);
        });
    }
});

// Sincronizar idioma entre pestañas
window.addEventListener('storage', function(e) {
    if (e.key === 'selectedLanguage') {
        const newLang = e.newValue || 'es';
        if (document.documentElement.lang !== newLang) {
            const selectEl = document.getElementById('languageSelect');
            if (selectEl) selectEl.value = newLang;
            try { changeLanguage(newLang); } catch (err) { console.error(err); }
        }
    }
});